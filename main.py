from contextlib import asynccontextmanager
from datetime import datetime
import os
from typing import AsyncIterator

import psycopg
from fastapi import FastAPI, HTTPException, Response, status
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field, field_validator


class TeamCreate(BaseModel):
    team_name: str = Field(min_length=1, max_length=100)

    @field_validator("team_name")
    @classmethod
    def strip_team_name(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("Team name cannot be empty")
        return value


class TeamResponse(BaseModel):
    id: int
    team_name: str
    created_at: datetime


def create_app(database_url: str | None = None) -> FastAPI:
    db_url = database_url or os.environ.get("DATABASE_URL")

    def connect() -> psycopg.Connection:
        if not db_url:
            raise RuntimeError(
                "DATABASE_URL is not set. Configure it with your PostgreSQL connection URL."
            )
        return psycopg.connect(db_url)

    @asynccontextmanager
    async def lifespan(_: FastAPI) -> AsyncIterator[None]:
        with connect() as connection:
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS teams (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    team_name VARCHAR(100) NOT NULL,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """
            )
        yield

    app = FastAPI(
        title="Cricket Tournament Teams API",
        description="Register, list, and remove teams for a tournament.",
    )
    app.add_middleware(
        CORSMiddleware,
        allow_origins=["http://127.0.0.1:5500", "http://localhost:5500"],
        allow_methods=["GET", "POST", "DELETE"],
        allow_headers=["Content-Type"],
    )

    @app.post(
        "/api/teams/generate",
        response_model=TeamResponse,
        status_code=status.HTTP_201_CREATED,
    )
    def register_team(team: TeamCreate) -> TeamResponse:
        with connect() as connection:
            row = connection.execute(
                """
                INSERT INTO teams (team_name)
                VALUES (%s)
                RETURNING id, team_name, created_at
                """,
                (team.team_name,),
            ).fetchone()

        if row is None:
            raise RuntimeError("The team was saved but could not be retrieved")
        return TeamResponse(id=row[0], team_name=row[1], created_at=row[2])

    @app.get("/api/teams", response_model=list[TeamResponse])
    def list_teams() -> list[TeamResponse]:
        with connect() as connection:
            rows = connection.execute(
                "SELECT id, team_name, created_at FROM teams ORDER BY id"
            ).fetchall()
        return [
            TeamResponse(id=row[0], team_name=row[1], created_at=row[2])
            for row in rows
        ]

    @app.delete("/api/teams/{team_id}", status_code=status.HTTP_204_NO_CONTENT)
    def delete_team(team_id: int) -> Response:
        with connect() as connection:
            cursor = connection.execute(
                "DELETE FROM teams WHERE id = %s",
                (team_id,),
            )
        if cursor.rowcount == 0:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="Team not found",
            )
        return Response(status_code=status.HTTP_204_NO_CONTENT)

    return app


app = create_app()
